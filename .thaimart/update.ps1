# Thaimart แนวทางที่เลือก · ชุดสำหรับ AI · อัปเดตเอง (Windows; made by the install command, kit 2026-11-03.2790b09)
#   powershell -File .thaimart/update.ps1          update now if the team link has a newer kit
#   powershell -File .thaimart/update.ps1 -Check   only say "มีรุ่นใหม่ <version>" when there is one (at most once a day)
#   powershell -File .thaimart/update.ps1 -Quiet   what the Claude Code SessionStart hook runs: silent unless it updated
# Same as update.sh: reads https://thaimart-final.charunmeedate.workers.dev/ai/version.txt (2 s at most); offline, an error or the same version = nothing; a newer kit
# runs the team link's install.ps1 here, then prints one line. .thaimart/settings.json {"autoUpdate": false} turns off
# -Quiet and -Check. Never in your home folder or at the root of a drive. Generated by link-tools/fin/ai/gen.mjs.
param([switch]$Check, [switch]$Quiet)
& {
  $ErrorActionPreference = 'Stop'
  $ProgressPreference = 'SilentlyContinue'
  try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch { }
  try {
    $Base = if ($env:THAIMART_AI_URL) { $env:THAIMART_AI_URL } else { 'https://thaimart-final.charunmeedate.workers.dev/ai' }
    $Dir = (Resolve-Path (Join-Path $PSScriptRoot '..')).ProviderPath
    $HomeDir = [Environment]::GetFolderPath('UserProfile')
    if ($Dir.TrimEnd('\', '/') -eq ([IO.Path]::GetPathRoot($Dir)).TrimEnd('\', '/')) { return }
    if ($HomeDir -and $Dir.TrimEnd('\', '/') -eq $HomeDir.TrimEnd('\', '/')) { return }
    Set-Location -LiteralPath $Dir
    if ($Check -or $Quiet) {
      $s = Join-Path $Dir '.thaimart/settings.json'
      if ((Test-Path -LiteralPath $s) -and ((Get-Content -Raw -LiteralPath $s) -match '"autoUpdate"\s*:\s*false')) { return }
    }
    try { [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12 } catch { }
    if ($Check) {
      $lc = Join-Path $Dir '.thaimart/last-check'; $today = (Get-Date).ToString('yyyy-MM-dd')
      if ((Test-Path -LiteralPath $lc) -and ((Get-Content -Raw -LiteralPath $lc).Trim() -eq $today)) { return }
      try { [IO.File]::WriteAllText($lc, "$today`n") } catch { }
    }
    $New = ''
    try { $New = ((Invoke-WebRequest -UseBasicParsing -TimeoutSec 2 -Uri "$Base/version.txt").Content | Out-String).Trim() } catch { return }
    if ($New -notmatch '^\d{4}-\d{2}-\d{2}\.[0-9a-f]{7}$') { return }
    $vf = Join-Path $Dir '.thaimart/version'
    $Have = if (Test-Path -LiteralPath $vf) { (Get-Content -Raw -LiteralPath $vf).Trim() } else { '' }
    if ($New -eq $Have) { if (-not $Check -and -not $Quiet) { Write-Host "ชุดแนวทาง Thaimart ล่าสุดแล้ว รุ่น $New" }; return }
    if ($Have -and ($New.Split('.')[0] -lt $Have.Split('.')[0])) { return }
    if ($Check) { Write-Host "มีรุ่นใหม่ $New"; return }
    $script = (Invoke-WebRequest -UseBasicParsing -TimeoutSec 30 -Uri "$Base/install.ps1").Content
    $env:THAIMART_AI_QUIET = '1'; $env:THAIMART_AI_URL = $Base
    try { Invoke-Expression $script } finally { Remove-Item Env:THAIMART_AI_QUIET -ErrorAction SilentlyContinue }
    $Got = if (Test-Path -LiteralPath $vf) { (Get-Content -Raw -LiteralPath $vf).Trim() } else { '' }
    if ($Got -eq $New) { Write-Host "อัปเดตชุดแนวทาง Thaimart เป็นรุ่น $New แล้ว" }
    elseif (-not $Quiet) { Write-Host 'อัปเดตไม่สำเร็จ ลองรันคำสั่งติดตั้งเดิมอีกครั้ง' }
  } catch {
    if (-not $Quiet) { Write-Host 'อัปเดตไม่สำเร็จ ลองรันคำสั่งติดตั้งเดิมอีกครั้ง' }
  }
}
exit 0
