#!/bin/sh
# Thaimart แนวทางที่เลือก · ชุดสำหรับ AI · อัปเดตเอง (made by the install command, kit 2026-11-03.2790b09; it is replaced on every update)
#   sh .thaimart/update.sh            update now if the team link has a newer kit (prints what it did)
#   sh .thaimart/update.sh --check    only say "มีรุ่นใหม่ <version>" when there is one; at most once a day (the day of the
#                                     last check is kept in .thaimart/last-check), silent otherwise
#   sh .thaimart/update.sh --quiet    what the Claude Code SessionStart hook starts in the background: silent
# It reads https://thaimart-final.charunmeedate.workers.dev/ai/version.txt (2 s at most). Offline, an error or the same version: it exits 0 and says nothing.
# A newer kit: it runs the team link's install.sh in this project (download, SHA-256 check, the marked blocks, both
# skills here and in ~/.claude/skills), then prints one line. .thaimart/settings.json {"autoUpdate": false} turns off the
# automatic runs (--quiet and --check); running it by hand still works. It only writes the kit's own paths, never as root,
# never in your home folder or at the root of a disk. Generated by link-tools/fin/ai/gen.mjs (template/update.sh.txt).
BASE="${THAIMART_AI_URL:-https://thaimart-final.charunmeedate.workers.dev/ai}"
CHECK=0; QUIET=0
for a in "$@"; do case "$a" in --check) CHECK=1 ;; --quiet) QUIET=1 ;; esac; done

# the project = the folder that holds .thaimart/
DIR=$(cd "$(dirname "$0")/.." 2>/dev/null && pwd -P) || exit 0
HOMEDIR=$(cd "${HOME:-/}" 2>/dev/null && pwd -P || printf '/')
[ "$DIR" != "/" ] && [ "$DIR" != "$HOMEDIR" ] || exit 0
[ "$(id -u 2>/dev/null)" != "0" ] || exit 0
cd "$DIR" || exit 0
# the team repo gets the kit by MR, not from here
git remote -v 2>/dev/null | grep -q 'uxi-team/thaimart-redesign' && exit 0

# autoUpdate false: no automatic runs
if [ $CHECK = 1 ] || [ $QUIET = 1 ]; then
  grep -Eq '"autoUpdate"[[:space:]]*:[[:space:]]*false' .thaimart/settings.json 2>/dev/null && exit 0
fi

# --check: once a day is enough (an AI runs it at the start of a task)
if [ $CHECK = 1 ]; then
  TODAY=$(date +%Y-%m-%d 2>/dev/null)
  [ -n "$TODAY" ] && [ "$(cat .thaimart/last-check 2>/dev/null)" = "$TODAY" ] && exit 0
fi

if command -v curl >/dev/null 2>&1; then NEW=$(curl -fsS --max-time 2 "$BASE/version.txt" 2>/dev/null)
elif command -v wget >/dev/null 2>&1; then NEW=$(wget -q -T 2 -t 1 -O - "$BASE/version.txt" 2>/dev/null)
else exit 0; fi
NEW=$(printf '%s' "$NEW" | tr -d ' \r\n')
case "$NEW" in [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9].[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]) ;; *) exit 0 ;; esac
# the day counts as checked only once the link answered (an offline morning checks again later)
[ $CHECK = 1 ] && [ -n "$TODAY" ] && printf '%s\n' "$TODAY" > .thaimart/last-check 2>/dev/null
HAVE=$(tr -d ' \r\n' < .thaimart/version 2>/dev/null)
if [ "$NEW" = "$HAVE" ]; then
  [ $CHECK = 0 ] && [ $QUIET = 0 ] && printf 'ชุดแนวทาง Thaimart ล่าสุดแล้ว รุ่น %s\n' "$NEW"
  exit 0
fi
# never go back to an older day
if [ -n "$HAVE" ] && [ "$(printf '%s\n%s\n' "${NEW%%.*}" "${HAVE%%.*}" | sort | head -n 1)" = "${NEW%%.*}" ] && [ "${NEW%%.*}" != "${HAVE%%.*}" ]; then exit 0; fi
if [ $CHECK = 1 ]; then printf 'มีรุ่นใหม่ %s\n' "$NEW"; exit 0; fi

TMP=$(mktemp -d 2>/dev/null || mktemp -d -t thaimart-up) || exit 0
trap 'rm -rf "$TMP"' EXIT INT TERM
if command -v curl >/dev/null 2>&1; then curl -fsS --max-time 30 "$BASE/install.sh" -o "$TMP/install.sh" 2>/dev/null || exit 0
else wget -q -T 30 -O "$TMP/install.sh" "$BASE/install.sh" 2>/dev/null || exit 0; fi
if [ $QUIET = 1 ]; then
  THAIMART_AI_QUIET=1 THAIMART_AI_URL="$BASE" sh "$TMP/install.sh" >/dev/null 2>&1 || exit 0
else
  THAIMART_AI_QUIET=1 THAIMART_AI_URL="$BASE" sh "$TMP/install.sh" || { printf 'อัปเดตไม่สำเร็จ ลองรันคำสั่งติดตั้งเดิมอีกครั้ง\n'; exit 0; }
fi
printf 'อัปเดตชุดแนวทาง Thaimart เป็นรุ่น %s แล้ว\n' "$(tr -d ' \r\n' < .thaimart/version 2>/dev/null)"
exit 0
